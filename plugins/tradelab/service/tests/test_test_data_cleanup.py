def test_cleanup_preview_targets_test_group_tree_without_mutating() -> None:
    suffix = uuid4().hex[:8]
    with SessionLocal(bind=get_engine()) as session:
        fixture = _create_strategy_tree(
            session,
            slug=f"test-group-preview-{suffix}",
            metadata={"visibility": "test", "purpose": "automated_test_fixture"},
            description="Integration test group",
        )
        user_group = _create_group(
            session,
            slug=f"user-group-preview-{suffix}",
            metadata={},
            description="User research group",
        )
        session.commit()

        summary = build_test_data_cleanup_plan(session)

        assert summary.mode == "preview"
        assert summary.group_count >= 1
        assert summary.strategy_count >= 1
        assert summary.version_count >= 1
        assert summary.bot_count >= 1
        assert fixture["group_id"] in summary.group_ids
        assert fixture["strategy_id"] in summary.strategy_ids
        assert fixture["version_id"] in summary.version_ids
        assert fixture["bot_id"] in summary.bot_ids
        assert user_group.id not in summary.group_ids

        session.expire_all()
        assert session.get(StrategyGroup, fixture["group_id"]).is_deleted is False
        assert session.get(Strategy, fixture["strategy_id"]).is_deleted is False
        assert session.get(StrategyVersion, fixture["version_id"]).is_deleted is False
        assert session.get(Bot, fixture["bot_id"]).is_deleted is False


def test_cleanup_apply_soft_deletes_target_tree_and_is_idempotent() -> None:
    suffix = uuid4().hex[:8]
    with SessionLocal(bind=get_engine()) as session:
        _create_group(
            session,
            slug=f"user-group-apply-{suffix}",
            metadata={"visibility": "private"},
            description="User-owned strategy group",
        )
        fixture = _create_strategy_tree(
            session,
            slug=f"test-group-apply-{suffix}",
            metadata={"visibility": "test", "purpose": "automated_test_fixture"},
            description="Integration test group",
        )
        session.commit()

        first = apply_test_data_cleanup(session, updated_by=CLEANUP_ACTOR)
        session.commit()
        session.expire_all()

        assert first.mode == "apply"
        assert fixture["group_id"] in first.group_ids
        assert session.get(StrategyGroup, fixture["group_id"]).is_deleted is True
        assert session.get(StrategyGroup, fixture["group_id"]).is_active is False
        assert session.get(Strategy, fixture["strategy_id"]).is_deleted is True
        assert session.get(StrategyVersion, fixture["version_id"]).is_deleted is True
        assert session.get(Bot, fixture["bot_id"]).is_deleted is True
        assert session.get(StrategyGroup, fixture["group_id"]).updated_by == CLEANUP_ACTOR

        second = apply_test_data_cleanup(session, updated_by=CLEANUP_ACTOR)
        session.commit()

        assert second.group_count == 0
        assert second.strategy_count == 0
        assert second.version_count == 0
        assert second.bot_count == 0


