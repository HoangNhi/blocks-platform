def test_cleanup_guard_rejects_baseline_and_workbench_targets() -> None:
    suffix = uuid4().hex[:8]
    with SessionLocal(bind=get_engine()) as session:
        baseline_like = _create_group(
            session,
            slug=f"test-group-baseline-guard-{suffix}",
            metadata={
                "visibility": "test",
                "purpose": "automated_test_fixture",
                "isBaseline": True,
            },
            description="Integration test group",
        )
        workbench_like = _create_group(
            session,
            slug=f"test-group-workbench-guard-{suffix}",
            metadata={
                "visibility": "workbench",
                "purpose": "automated_test_fixture",
            },
            description="Integration test group",
        )
        session.commit()

        with pytest.raises(CleanupGuardError) as baseline_error:
            build_test_data_cleanup_plan(session)
        assert str(baseline_like.id) in str(baseline_error.value)
        assert "baseline" in str(baseline_error.value).lower()

        baseline_like.metadata_ = {"visibility": "test", "purpose": "automated_test_fixture"}
        session.flush()

        with pytest.raises(CleanupGuardError) as workbench_error:
            build_test_data_cleanup_plan(session)
        assert str(workbench_like.id) in str(workbench_error.value)
        assert "workbench" in str(workbench_error.value).lower()


