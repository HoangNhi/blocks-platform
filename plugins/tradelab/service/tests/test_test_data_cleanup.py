def test_cleanup_cli_apply_commits_and_uses_actor(monkeypatch, capsys) -> None:
    from tradelab_api.tools import cleanup_test_data

    class FakeSession:
        committed = False
        rolled_back = False

        def commit(self):
            self.committed = True

        def rollback(self):
            self.rolled_back = True

        def close(self):
            pass

    fake_session = FakeSession()
    received: dict[str, str] = {}

    def fake_apply(session, *, updated_by: str):
        received["updated_by"] = updated_by
        return cleanup_test_data.TestDataCleanupSummary(mode="apply")

    monkeypatch.setattr(cleanup_test_data, "get_engine", lambda: object())
    monkeypatch.setattr(cleanup_test_data, "SessionLocal", lambda bind=None: fake_session)
    monkeypatch.setattr(cleanup_test_data, "apply_test_data_cleanup", fake_apply)

    exit_code = cleanup_test_data.main(["--apply", "--updated-by", "pytest-cli"])
    captured = capsys.readouterr()

    assert exit_code == 0
    assert '"mode": "apply"' in captured.out
    assert received["updated_by"] == "pytest-cli"
    assert fake_session.committed is True
    assert fake_session.rolled_back is False


def _create_group(
    session,
    *,
    slug: str,
    metadata: dict[str, object],
    description: str,
) -> StrategyGroup:
    group = StrategyGroup(
        name=f"Cleanup {slug}",
        slug=slug,
        description=description,
        metadata_=metadata,
        created_by="pytest-cleanup",
    )
    session.add(group)
    session.flush()
    session.refresh(group)
    return group


def _soft_delete_pytest_cleanup_rows() -> None:
    with SessionLocal(bind=get_engine()) as session:
        for model in (Bot, StrategyVersion, Strategy, StrategyGroup):
            rows = session.query(model).filter(model.created_by == "pytest-cleanup").all()
            for row in rows:
                row.is_active = False
                row.is_deleted = True
                row.updated_by = "pytest-cleanup-fixture"
        session.commit()


def _create_strategy_tree(
    session,
    *,
    slug: str,
    metadata: dict[str, object],
    description: str,
) -> dict[str, UUID]:
    group = _create_group(session, slug=slug, metadata=metadata, description=description)
    strategy = Strategy(
        strategy_group_id=group.id,
        name=f"Strategy {slug}",
        slug=f"strategy-{slug}",
        description="Automated cleanup test strategy",
        status="active",
        runtime_config={},
        risk_config={},
        metadata_=dict(metadata),
        created_by="pytest-cleanup",
    )
    session.add(strategy)
    session.flush()
    version = StrategyVersion(
        strategy_id=strategy.id,
        version_number=1,
        source_code="def on_candle(ctx):\n    return None\n",
        source_hash=f"hash-{slug}",
        validation_status="valid",
        validation_message=None,
        created_by="pytest-cleanup",
    )
    session.add(version)
    session.flush()
    strategy.current_version_id = version.id
    bot = Bot(
        strategy_id=strategy.id,
        strategy_version_id=version.id,
        name=f"Bot {slug}",
        mode="backtest",
        status="draft",
        symbol="BTCUSDT",
        timeframe="1h",
        runtime_config={},
        risk_config={},
        metadata_=dict(metadata),
        created_by="pytest-cleanup",
    )
    session.add(bot)
    session.flush()
    return {
        "group_id": group.id,
        "strategy_id": strategy.id,
        "version_id": version.id,
        "bot_id": bot.id,
    }
